/* Лента возвращается туда, где человек её оставил.
 *
 * Разбор жалобы — это часы в ленте на семнадцать тысяч страниц. Любая
 * перезагрузка (обновил вкладку, уснул ноутбук, вышел и вернулся) сбрасывала
 * ленту в самое начало, и место приходилось искать заново по номеру страницы,
 * который человек не помнит.
 *
 * Место — это страница, фильтры и кадр, на котором остановились. Фильтры сюда
 * входят обязательно: страница 700 без них показывает совсем другие кадры.
 *
 *   node место-в-ленте.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
const п = (имя, ок, д = "") => { console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (д ? " — " + д : "")); if (!ок) провалы.push(имя); };

const хранилище = {};
const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: {
    getItem: k => (k in хранилище ? хранилище[k] : null),
    setItem: (k, v) => { хранилище[k] = String(v); },
  },
  state: { внутри: {} },
  память: src => (мир.state.внутри[src] = мир.state.внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n), NBSP: " ", взять: async () => ({}), сказать: () => {},
  URLSearchParams,
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

// ── на какой странице лежит кадр ─────────────────────────────────────────
// Кадры копятся: долистав до низа, человек видит четыре страницы подряд одной
// сеткой. Чтобы вернуться к сотому кадру, надо знать, что он на второй.
const стр = мир.страницаКадра;
п("первый кадр — на своей же странице", стр(0, 0, 60) === 0, String(стр(0, 0, 60)));
п("шестидесятый — на следующей", стр(0, 60, 60) === 1, String(стр(0, 60, 60)));
п("считается от первой показанной", стр(56, 61, 60) === 57, String(стр(56, 61, 60)));
п("без размера страницы берём шестьдесят", стр(0, 120) === 2, String(стр(0, 120)));

// ── что сохраняется и что читается ───────────────────────────────────────
const src = "moderation:shelf";
мир.запомнитьМесто(src, { page: 57, id: "кадр7", kind: "Холсты", adult: "hide", group: "" });
const место = мир.вспомнитьМесто(src);
п("место читается обратно", место && место.page === 57 && место.id === "кадр7",
  JSON.stringify(место));
п("место каждого блока своё", мир.вспомнитьМесто("другой:блок") === null,
  String(мир.вспомнитьМесто("другой:блок")));

// Хранилище правят руками и чистят браузером — мусор не должен ронять ленту.
хранилище["tessera:spot:битый"] = "{это не json";
п("битая запись — как будто места нет", мир.вспомнитьМесто("битый") === null,
  String(мир.вспомнитьМесто("битый")));

// ── когда место применяется ──────────────────────────────────────────────
const свежая = {};
п("на пустой памяти место применяется",
  мир.применитьМесто(свежая, место) === "кадр7" && свежая.page === 57 &&
    свежая.kind === "Холсты" && свежая.adult === "hide",
  JSON.stringify(свежая));

// Человек уже листает — значит он сам выбрал, где быть. Возвращать его к
// прошлому месту в такой момент значит отбирать управление.
const занятая = { page: 3, kind: "" };
п("на живой памяти место не трогает ничего",
  мир.применитьМесто(занятая, место) === null && занятая.page === 3,
  JSON.stringify(занятая));
п("места нет — и применять нечего", мир.применитьМесто({}, null) === null);

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
