/* Лента дописывается снизу, а не сменяется целиком.
 *
 * Модератор просматривает поток кадров подряд: долистал шестьдесят — нужны
 * следующие шестьдесят. Раньше за ними надо было тянуться к кнопке «Дальше»
 * внизу, и каждая страница начиналась сверху, с потерей места, на котором
 * человек остановился.
 *
 * Листалка при этом остаётся: страниц восемь тысяч, и до конца июня
 * прокруткой не добраться — туда прыгают по номеру.
 *
 *   node догрузка-ленты.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
const п = (имя, ок, д = "") => { console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (д ? " — " + д : "")); if (!ок) провалы.push(имя); };

const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: { getItem: () => null, setItem: () => {} },
  state: { внутри: {} },
  память: src => (мир.state.внутри[src] = мир.state.внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n), NBSP: " ", взять: async () => ({}), сказать: () => {},
  URLSearchParams,
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

const след = мир.следующаяСтраница;

п("за первой страницей идёт вторая", след(0, 2004) === 1, String(след(0, 2004)));
п("за пятой — шестая", след(4, 2004) === 5, String(след(4, 2004)));

// Конец ленты: дальше грузить нечего, и наблюдатель должен замолчать, а не
// долбить сервер пустыми страницами при каждом движении колеса.
п("на последней странице догружать нечего", след(2003, 2004) === null,
  String(след(2003, 2004)));
п("одна страница — сразу конец", след(0, 1) === null, String(след(0, 1)));
п("пустая лента ничего не догружает", след(0, 0) === null, String(след(0, 0)));

// Число страниц приходит с сервера и может отсутствовать: модуль не ответил,
// фильтр вернул пустоту. Догрузка в таком случае молчит.
п("без числа страниц молчим", след(0, undefined) === null && след(0, null) === null,
  след(0, undefined) + " " + след(0, null));

// Подпись листалки говорит, сколько уже показано: «страницы 1–3 из 2004».
// Одна страница остаётся одной страницей, без тире.
const подпись = мир.показаноСтраниц;
п("одна страница называется номером", подпись(0, 0) === "1", подпись(0, 0));
п("несколько — диапазоном", подпись(0, 2) === "1–3", подпись(0, 2));
п("диапазон считается от первой показанной", подпись(56, 58) === "57–59", подпись(56, 58));

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
