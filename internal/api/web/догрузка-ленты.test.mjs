/* Лента дописывается снизу, а не сменяется целиком.
 *
 * Модератор просматривает поток кадров подряд: долистал шестьдесят — нужны
 * следующие шестьдесят. Раньше за ними надо было тянуться к кнопке «Дальше»
 * внизу, и каждая страница начиналась сверху, с потерей места, на котором
 * человек остановился.
 *
 * Листалка при этом остаётся: страниц восемь тысяч, и до конца июня
 * прокруткой не добраться — туда прыгают по номеру.
 *
 *   node догрузка-ленты.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
const п = (имя, ок, д = "") => { console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (д ? " — " + д : "")); if (!ок) провалы.push(имя); };

const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: { getItem: () => null, setItem: () => {} },
  state: { внутри: {} },
  память: src => (мир.state.внутри[src] = мир.state.внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n), NBSP: " ", взять: async () => ({}), сказать: () => {},
  URLSearchParams,
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

const след = мир.следующаяСтраница;

п("за первой страницей идёт вторая", след(0, 2004) === 1, String(след(0, 2004)));
п("за пятой — шестая", след(4, 2004) === 5, String(след(4, 2004)));

// Конец ленты: дальше грузить нечего, и наблюдатель должен замолчать, а не
// долбить сервер пустыми страницами при каждом движении колеса.
п("на последней странице догружать нечего", след(2003, 2004) === null,
  String(след(2003, 2004)));
п("одна страница — сразу конец", след(0, 1) === null, String(след(0, 1)));
п("пустая лента ничего не догружает", след(0, 0) === null, String(след(0, 0)));

// Число страниц приходит с сервера и может отсутствовать: модуль не ответил,
// фильтр вернул пустоту. Догрузка в таком случае молчит.
п("без числа страниц молчим", след(0, undefined) === null && след(0, null) === null,
  след(0, undefined) + " " + след(0, null));

// Подпись листалки говорит, сколько уже показано: «страницы 1–3 из 2004».
// Одна страница остаётся одной страницей, без тире.
const подпись = мир.показаноСтраниц;
п("одна страница называется номером", подпись(0, 0) === "1", подпись(0, 0));
п("несколько — диапазоном", подпись(0, 2) === "1–3", подпись(0, 2));
п("диапазон считается от первой показанной", подпись(56, 58) === "57–59", подпись(56, 58));

// ── Запас: следующая страница грузится заранее, пока человек смотрит эту.
// Холодная страница — три с половиной секунды на ответ и ещё по 0,4 секунды
// на каждый из сорока недостающих кадров; без запаса это полминуты ожидания
// у пустого низа ленты.

const звонки = [];
const запас = мир.создатьЗапас(стр => { звонки.push(стр); return Promise.resolve({ page: стр }); });
запас.приготовить(1);
запас.приготовить(1);
п("одна и та же страница грузится в запас один раз", звонки.length === 1, звонки.join(","));
const взяли = запас.забрать(1);
п("догрузка забирает готовый запас", !!взяли && typeof взяли.then === "function");
п("забранный запас второй раз не отдаётся", запас.забрать(1) === undefined);
запас.приготовить(2);
п("чужая страница из запаса не отдаётся", запас.забрать(3) === undefined && звонки.join(",") === "1,2",
  звонки.join(","));
п("приготовить «ничего» ничего не грузит", (запас.приготовить(null), звонки.length === 2));

// Отказ запаса не должен ломать догрузку: забрать возвращает тот же
// отказ, и догрузка покажет его в маячке, как и без запаса.
const плохой = мир.создатьЗапас(() => Promise.reject(new Error("нет связи")));
плохой.приготовить(5);
const отказ = await плохой.забрать(5).then(() => "пришло", e => e.message);
п("отказ запаса доходит до догрузки", отказ === "нет связи", отказ);

// Картинки запаса: звук рисовать нечем, у кадра без адреса брать нечего.
const адреса = мир.адресаЗапаса([
  { id: "a", url: "/api/file?src=m:thumb&id=a" },
  { id: "b", url: "/api/file?src=m:thumb&id=b", audio: true },
  { id: "c", url: "" },
  { id: "d", url: "/api/file?src=m:thumb&id=d&path=x" },
]);
п("в запас идут только кадры с картинкой", адреса.length === 2, адреса.join(" "));
п("адрес запаса тот же, что у плитки", адреса[0] === "/tessera/api/file?src=m:thumb&id=a", адреса[0]);

// Подгрузка картинок не забивает очередь модулей: у ядра их четыре разом, и
// запас не имеет права занять все — щелчок по кадру встал бы в очередь.
let сейчас = 0, пик = 0;
const готово = [];
await мир.подтянутьКартинки(["1", "2", "3", "4", "5", "6", "7"], 2, адрес => {
  сейчас++; пик = Math.max(пик, сейчас);
  return new Promise(r => setTimeout(() => { сейчас--; готово.push(адрес); r(); }, 5));
});
п("картинки подтягиваются не больше двух разом", пик === 2, "пик " + пик);
п("подтянуты все картинки", готово.length === 7, String(готово.length));
let стоп = false, после = 0;
await мир.подтянутьКартинки(["1", "2", "3", "4"], 1, () => { после++; стоп = true; return Promise.resolve(); }, () => стоп);
п("смена фильтра останавливает подгрузку", после === 1, String(после));

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
