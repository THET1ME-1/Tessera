/* Номер страницы в ленте вводится руками.
 *
 * Стрелками до нужного места не дойти: страниц две тысячи, а разбор жалобы
 * часто начинается с «покажи, что было в конце июня». Поле принимает номер,
 * какой человек видит на экране (с единицы), и отдаёт номер, каким его знает
 * сервер (с нуля).
 *
 *   node страница-ленты.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
const п = (имя, ок, д = "") => { console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (д ? " — " + д : "")); if (!ок) провалы.push(имя); };

const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: { getItem: () => null, setItem: () => {} },
  state: { внутри: {} },
  память: src => (мир.state.внутри[src] = мир.state.внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n), NBSP: " ", взять: async () => ({}), сказать: () => {},
  URLSearchParams,
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

const н = (ввод, всего = 2004) => мир.номерСтраницы(ввод, всего);

п("страница с единицы на экране, с нуля на сервере", н("57") === 56, String(н("57")));
п("первая страница", н("1") === 0, String(н("1")));
п("последняя страница", н("2004") === 2003, String(н("2004")));

// Промах не должен уводить в пустоту: за краем ленты сервер отдаёт пустую
// страницу, и она читается как «файлы кончились».
п("больше последней — прижимается к последней", н("99999") === 2003, String(н("99999")));
п("ноль и минус — прижимаются к первой", н("0") === 0 && н("-3") === 0,
  н("0") + " " + н("-3"));

// Пробелы в числе — свои: подпись рядом пишет «из 2 004», и это же значение
// человек копирует в поле.
п("пробелы внутри числа не мешают", н("2 004") === 2003 && н(" 57 ") === 56,
  н("2 004") + " " + н(" 57 "));
п("неразрывный пробел тоже", н("2 004") === 2003, String(н("2 004")));

// Пустое или буквы — не переход, а отказ: иначе случайное нажатие уносит
// человека с той страницы, которую он разбирает.
п("мусор не переводит никуда",
  н("") === null && н("абв") === null && н("12ф") === null,
  [н(""), н("абв"), н("12ф")].join(" "));
п("дробное не переводит никуда", н("2,5") === null, String(н("2,5")));

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
