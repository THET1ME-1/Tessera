/* Несколько кадров скачиваются одной пачкой.
 *
 * Разбор жалобы — это редко один снимок: под замком лежит альбом, у пары
 * набирается десяток спорных кадров, и открывать каждый в лайтбоксе ради
 * кнопки «Скачать оригинал» долго. Галочка на плитке собирает кадры, полоса
 * снизу отправляет их скачиваться подряд.
 *
 *   node выбор-кадров.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
const п = (имя, ок, д = "") => { console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (д ? " — " + д : "")); if (!ок) провалы.push(имя); };

const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: { getItem: () => null, setItem: () => {} },
  state: { внутри: {} },
  память: src => (мир.state.внутри[src] = мир.state.внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n), NBSP: " ", взять: async () => ({}), сказать: () => {},
  URLSearchParams,
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

// ── склонение под числом кадров ──────────────────────────────────────────
const кадров = мир.кадровСловом;
п("один кадр", кадров(1) === "1 кадр", кадров(1));
п("два кадра", кадров(2) === "2 кадра", кадров(2));
п("пять кадров", кадров(5) === "5 кадров", кадров(5));
п("одиннадцать — кадров, а не кадр", кадров(11) === "11 кадров", кадров(11));
п("двадцать один кадр", кадров(21) === "21 кадр", кадров(21));
п("сто четырнадцать кадров", кадров(114) === "114 кадров", кадров(114));

// ── что уходит на скачивание ─────────────────────────────────────────────
const адреса = мир.адресаВыбранных;
const карта = { a1: "/api/file?id=a1&download=1", a2: "/api/file?id=a2&download=1" };

п("порядок выбора сохраняется",
  адреса(["a2", "a1"], карта).join(",") === "/tessera/api/file?id=a2&download=1,/tessera/api/file?id=a1&download=1",
  адреса(["a2", "a1"], карта).join(","));

// Панель живёт в подпапке (/tessera/), а модуль называет путь от корня: без
// пересчёта браузер уходил бы на корень домена и получал пустоту.
п("адрес считается от корня панели",
  адреса(["a1"], карта)[0] === "/tessera/api/file?id=a1&download=1",
  адреса(["a1"], карта)[0]);

// Выбор переживает смену фильтра и догрузку страниц, поэтому в наборе может
// остаться кадр, которого в текущей ленте уже нет. Такой пропускаем: адреса
// у него взять неоткуда.
п("кадр без адреса пропускается", адреса(["a1", "исчез"], карта).length === 1,
  String(адреса(["a1", "исчез"], карта).length));
п("пустой выбор — пустая пачка", адреса([], карта).length === 0,
  String(адреса([], карта).length));

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
