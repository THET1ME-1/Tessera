/* Ссылка ленты собирается из памяти блока — и пара в ней такой же фильтр,
 * как вид файла и возрастная пометка.
 *
 * Проверяется без браузера: файл заготовок исполняется в песочнице, а память
 * и корень панели подставляются снаружи. Ловит две вещи, которые ломают
 * разбор жалобы: пропавший из ссылки `group` (лента показывает всех подряд) и
 * адрес от корня домена вместо места, где стоит панель.
 *
 *   node ссылка-ленты.test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "node:vm";

const провалы = [];
function проверка(имя, ок, добавка = "") {
  console.log((ок ? "ОК   " : "ПЛОХО") + " " + имя + (добавка ? " — " + добавка : ""));
  if (!ок) провалы.push(имя);
}

const внутри = {};
const мир = {
  console,
  document: { getElementById: () => null },
  localStorage: { getItem: () => null, setItem: () => {} },
  state: { внутри },
  память: src => (внутри[src] = внутри[src] || {}),
  адрес: путь => "/tessera/" + путь.replace(/^\//, ""),
  fmt: n => String(n),
  NBSP: " ",
  взять: async () => ({}),
  сказать: () => {},
};
vm.createContext(мир);
vm.runInContext(readFileSync(new URL("./blocks.js", import.meta.url), "utf8"), мир);

const src = "moderation:shelf";
const моё = мир.память(src);

проверка("пустая память даёт первую страницу без фильтров",
  мир.ссылкаЛенты(src) === "/tessera/api/query?src=moderation%3Ashelf&page=0",
  мир.ссылкаЛенты(src));

Object.assign(моё, { page: 2, kind: "Холсты", adult: "hide", group: "rd656e16ea471f3" });
const с_парой = мир.ссылкаЛенты(src);
проверка("пара уходит на сервер", с_парой.includes("&group=rd656e16ea471f3"), с_парой);
проверка("вид и пометка не потерялись",
  с_парой.includes("&kind=") && с_парой.includes("&adult=hide"), с_парой);
проверка("страница взята из памяти", с_парой.includes("&page=2"), с_парой);

delete моё.group;
проверка("без пары параметра нет вовсе", !мир.ссылкаЛенты(src).includes("group"),
  мир.ссылкаЛенты(src));

моё.group = "пара с пробелом";
проверка("id пары экранируется",
  мир.ссылкаЛенты(src).includes("group=" + encodeURIComponent("пара с пробелом")),
  мир.ссылкаЛенты(src));

// Плотность сетки — дело браузера, серверу она не нужна: лишний параметр
// сбивает кэш ядра и ничего не меняет в ответе.
delete моё.group;
моё.cols = 7;
проверка("плотность сетки на сервер не уходит", !мир.ссылкаЛенты(src).includes("cols"),
  мир.ссылкаЛенты(src));

console.log(провалы.length ? "\nПРОВАЛЫ: " + провалы.join(", ") : "\nвсё зелено");
process.exit(провалы.length ? 1 : 0);
