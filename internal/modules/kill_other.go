//go:build !unix

package modules

import (
	"os/exec"
	"time"
)

// оборвать: на системах без групп процессов остаётся подстраховка ожиданием.
// Потомки зависшего модуля переживут его смерть, поэтому такие модули лучше
// писать одним процессом.
func оборвать(cmd *exec.Cmd) {
	cmd.WaitDelay = time.Second
}
