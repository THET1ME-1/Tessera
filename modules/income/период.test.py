"""Доход за период считается по дням, а не отдаётся месячной суммой.

Регресс на поломку 15.08.2026: переключатель «7 дней / 30 дней / всё время»
не менял ни одного числа на вкладке дохода. Сбор идёт командой `collect`, где
периода нет вовсе, и панель показывала месяц при любом выборе — со стороны
это выглядит как неверный расчёт, а не как неработающая кнопка.

    python3 период.test.py
"""
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import main  # noqa: E402

СВОДКА = {
    "sources": {
        "lava": {"ok": True, "title": "lava", "currency": "USD", "month": 100,
                 "days": [{"d": "2026-08-01", "v": 10}, {"d": "2026-08-05", "v": 20},
                          {"d": "2026-08-14", "v": 70}]},
        "rsya": {"ok": True, "title": "Яндекс", "currency": "USD", "month": 30,
                 "days": [{"d": "2026-08-01", "v": 5}, {"d": "2026-08-14", "v": 25}]},
        # Источник без дневной разбивки в счёт за период не идёт вовсе.
        "play": {"ok": True, "title": "Google Play", "currency": "USD", "month": 50},
        "мёртвый": {"ok": False, "title": "Не подключён"},
    },
    "totals": {"month": 180},
}
ИСТОРИЯ = {"months": [{"m": "2026-07", "total": 53.39}, {"m": "2026-08", "total": 170}],
           "years": [{"y": 2026, "total": 223.39}]}


class Период(unittest.TestCase):
    def test_неделя_считается_по_дням(self):
        д = main.за_период(СВОДКА, ИСТОРИЯ, "2026-08-10", "2026-08-15")
        self.assertEqual(д["value"], 95)          # 70 lava + 25 Яндекс
        self.assertIn("2026-08-10", д["sub"])

    def test_месяц_больше_недели(self):
        неделя = main.за_период(СВОДКА, ИСТОРИЯ, "2026-08-10", "2026-08-15")["value"]
        месяц = main.за_период(СВОДКА, ИСТОРИЯ, "2026-08-01", "2026-08-15")["value"]
        self.assertGreater(месяц, неделя)
        self.assertEqual(месяц, 130)              # 100 lava + 30 Яндекс

    def test_источник_без_дней_назван_в_подписи(self):
        # Молча выбросить Google Play нельзя: сумма станет меньше настоящей, а
        # понять почему будет неоткуда.
        д = main.за_период(СВОДКА, ИСТОРИЯ, "2026-08-01", "2026-08-15")
        self.assertIn("Google Play", д["sub"])
        self.assertNotIn("Не подключён", д["sub"])

    def test_всё_время_берёт_архив_а_не_дни(self):
        # Подневные данные живут месяц, архив — с февраля. За «всё время»
        # считать по дням значит потерять всё, что было раньше.
        д = main.за_всё(СВОДКА, ИСТОРИЯ)
        self.assertEqual(д["value"], 233.39)      # 53.39 июль + 180 свежий август
        self.assertEqual(д["sub"], "за всё время")

    def test_запрос_с_границами_отвечает_периодом(self):
        # Проверка договора с ядром: оно шлёт from/to третьим аргументом.
        параметры = {"from": "2026-08-10", "to": "2026-08-15"}
        д = main.за_период(СВОДКА, ИСТОРИЯ, параметры["from"], параметры["to"])
        self.assertNotEqual(д["value"], СВОДКА["totals"]["month"])

    def test_нулевой_год_означает_всё_время(self):
        # Ядро присылает «всё время» границей 0000-01-01, а не пустотой.
        self.assertTrue("0000-01-01" <= "2000-01-01")


if __name__ == "__main__":
    unittest.main(verbosity=2)
