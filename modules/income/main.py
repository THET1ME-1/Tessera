#!/usr/bin/env python3
"""Модуль «Доход»: показывает деньги из рекламных кабинетов и магазинов.

Модуль НЕ ходит в чужие API сам. Он читает готовые сводки, которые кладёт
отдельный сбор по расписанию, и превращает их в блоки панели.

Так сделано намеренно. Поход в четыре чужих кабинета — дело долгое, с ключами,
лимитами и отказами; складывать его в путь запроса от панели значит получить
экран, который грузится минуту и падает, когда у Google плохой день. Сбор
отвечает за «сходить и записать», модуль — за «показать записанное».

    python3 main.py collect            все блоки разом
    python3 main.py query month '{}'   один блок

Откуда читать, задаётся в module.json:

    "files": { "summary": "/opt/.../.income.json",
               "history": "/opt/.../.income_history.json" }
"""

import json
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def настройки():
    with open(os.path.join(ЗДЕСЬ, "module.json"), encoding="utf-8") as f:
        return json.load(f).get("files", {})


def прочитать(путь):
    """Сводки пишутся ASCII-экранированными, поэтому кодировку не угадываем."""
    if not путь or not os.path.exists(путь):
        return None
    try:
        with open(путь, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        print(f"{путь}: {e}", file=sys.stderr)
        return None


def деньги(v):
    return 0.0 if v is None else round(float(v), 2)


# ── блоки ───────────────────────────────────────────────────────────────────

def блоки(сводка, история):
    итог = {}
    if not сводка:
        return итог

    totals = сводка.get("totals", {})
    источники = сводка.get("sources", {})
    месяцы = (история or {}).get("months", [])

    # Плитки за периоды. Разбивка под числом — сколько дал каждый источник.
    части = [{"name": д.get("title", ключ), "value": деньги(д.get("month"))}
             for ключ, д in источники.items() if д.get("ok")]
    части.sort(key=lambda p: -p["value"])

    прирост = None
    if len(месяцы) >= 2 and месяцы[-2].get("total"):
        было, стало = месяцы[-2]["total"], месяцы[-1]["total"]
        прирост = (стало - было) / было * 100

    итог["month"] = {"value": деньги(totals.get("month")), "sub": "с начала месяца",
                     "format": "money", "parts": части}
    if прирост is not None:
        итог["month"]["delta"] = прирост

    заСегодня = [{"name": д.get("title", к), "value": деньги(д.get("today"))}
                 for к, д in источники.items() if д.get("ok") and д.get("today")]
    заСегодня.sort(key=lambda p: -p["value"])
    итог["today"] = {"value": деньги(totals.get("today")), "sub": "с полуночи",
                     "format": "money", "parts": заСегодня}
    итог["yesterday"] = {"value": деньги(totals.get("yesterday")), "sub": "полные сутки",
                         "format": "money"}

    # История собирается ночью, а сводка обновляется каждые двадцать минут.
    # Без поправки год оказывается меньше собственного последнего месяца.
    годы = (история or {}).get("years", [])
    за_год = деньги(годы[0].get("total")) if годы else 0
    if месяцы and totals.get("month") is not None:
        за_год = деньги(за_год - деньги(месяцы[-1].get("total")) + деньги(totals.get("month")))
    итог["year"] = {"value": за_год, "format": "money",
                    "sub": f"за {годы[0].get('y')} год, с поправкой на сегодня" if годы else "за год"}

    # Таблица источников: сегодня, месяц и прошлый месяц рядом.
    строки = []
    for ключ, д in источники.items():
        if not д.get("ok"):
            # Источник без ключа не ломает сводку: он честно говорит, что не
            # подключён, иначе непонятно, почему в сумме нет рекламы Google.
            строки.append([д.get("title", ключ), None, None, None])
            continue
        строки.append([д.get("title", ключ), деньги(д.get("today")),
                       деньги(д.get("month")), деньги(д.get("prev_month"))])
    строки.sort(key=lambda r: -(r[2] or 0))
    итог["sources"] = {"cols": ["Источник", "Сегодня", "Месяц", "Прошлый месяц"],
                       "rows": строки, "barCol": 2, "format": "money"}

    # Месяцы столбиками.
    if месяцы:
        итог["history"] = {
            "items": [{"label": м["m"], "parts": [{"v": деньги(м.get("total"))}]} for м in месяцы],
            "unit": "долларов", "format": "money",
        }

    # Продажи: сколько людей купили и каким путём.
    продано = сводка.get("sold", {})
    if продано:
        каналы = продано.get("plus", {})
        итог["sold"] = {
            "value": продано.get("plus_total", 0),
            "sub": "оплат полного доступа",
            "parts": [{"name": имя, "value": число} for имя, число in каналы.items()],
        }

    # Покупки по магазинам: где сколько купили и на сколько.
    таблица = покупки(сводка)
    if таблица["rows"]:
        итог["purchases"] = таблица

    # География рекламы: у кого её показывают.
    рся = источники.get("rsya", {})
    if рся.get("geo"):
        итог["geo"] = {"rows": [{"name": g["name"], "value": деньги(g["v"])} for g in рся["geo"][:8]],
                       "unit": 1, "unitLabel": "долларов на кусочек", "format": "money"}
    if рся.get("os"):
        итог["os"] = {"items": [{"name": o["name"], "value": деньги(o["v"])} for o in рся["os"]],
                      "format": "money"}

    # Оговорки источников — на видном месте, а не в чужой голове.
    оговорки = [f"{д.get('title', к)}: {д['note'].rstrip('.')}." for к, д in источники.items()
                if д.get("note")]
    курс = сводка.get("rates", {}).get("rub_per_usd")
    if курс:
        оговорки.append(f"Рубли и евро приведены к доллару по курсу дня сборки: {round(курс, 2)} ₽.")
    if оговорки:
        итог["notes"] = {"text": " ".join(оговорки)}

    return итог


# Названия товаров в магазинах свои у каждого: Google зовёт полный доступ
# `togetherly_plus`, lava — «Togetherly+ — полный доступ», Apple — своим id.
# В таблице это один и тот же Плюс, и читаться он должен одинаково.
ТОВАРЫ = {
    "togetherly_plus": "Плюс",
    "togetherly.plus": "Плюс",
    "togetherly_plus_gift": "Плюс в подарок",
    "togetherly+ — полный доступ": "Плюс",
    "mood_pack.moti": "Набор настроений",
    "mood_pack:moti": "Набор настроений",
    "донат": "Донат",
}


def человечно(имя):
    return ТОВАРЫ.get(str(имя or "").strip().lower(), имя)


def покупки(сводка):
    """Что купили в магазинах за месяц: штук, денег, средний чек.

    Деньги приезжают готовыми долларами — комиссию магазина, курс и возвраты
    считает сбор. Модуль складывает строки и делит одно на другое.

    Реклама сюда не попадает: у неё нет ни покупок, ни чека, и строка «Яндекс,
    318 $» в таблице покупок читалась бы как проданный доступ.
    """
    # Один товар в одном магазине — одна строка. lava ведёт счёт по валютам, и
    # сто покупок Плюса в рублях и семь в долларах приезжают двумя рядами с
    # одинаковым именем; в таблице они читались бы как два разных товара.
    свод = {}
    for ключ, ист in ((сводка or {}).get("sources") or {}).items():
        for товар in (ист.get("purchases") or []):
            штук = int(товар.get("count") or 0)
            if not штук:
                continue
            имя, где = человечно(товар.get("name") or ключ), ист.get("title", ключ)
            строка = свод.setdefault((имя, где), {"штук": 0, "денег": 0.0})
            строка["штук"] += штук
            строка["денег"] += float(товар.get("usd") or 0)

    строки = [[имя, где, д["штук"], деньги(д["денег"]), деньги(д["денег"] / д["штук"])]
              for (имя, где), д in свод.items()]
    строки.sort(key=lambda r: -r[3])
    return {"cols": ["Покупка", "Где", "Штук", "Денег", "Средний чек"],
            "rows": строки, "barCol": 3, "format": "money"}


def за_период(сводка, история, от, до):
    """Доход за произвольный отрезок — по подневным данным источников.

    Все четыре источника ведут разбивку по дням: Яндекс и AdMob отдают её
    своими API, lava собирается из писем продавца, Google Play — из отчёта
    продаж по колонке «Order Charged Date». Поэтому «7 дней» и «30 дней»
    считаются честно, а не показывают месячную сумму, как было до 15.08.2026:
    переключатель жался, число не двигалось, и это читалось как неверный счёт.

    Пустые границы означают «всё время»: тогда берём накопленное из истории.
    """
    источники = сводка.get("sources") or {}
    части, всего = [], 0.0
    пропущено = []
    for ключ, ист in источники.items():
        if not ист.get("ok"):
            continue
        дни = ист.get("days") or []
        if not дни:
            # Источник без подневной разбивки в счёт за период не идёт: месячная
            # сумма внутри недели соврала бы больше, чем её отсутствие.
            пропущено.append(ист.get("title", ключ))
            continue
        сумма = sum(деньги(д.get("v")) for д in дни
                    if (not от or д.get("d", "") >= от) and (not до or д.get("d", "") <= до))
        if сумма:
            части.append({"name": ист.get("title", ключ), "value": деньги(сумма)})
            всего += сумма
    части.sort(key=lambda p: -p["value"])
    хвост = f"с {от} по {до}" if от and до else "за всё время"
    if пропущено:
        хвост += " · без " + ", ".join(пропущено)
    return {"value": деньги(всего), "sub": хвост, "format": "money", "parts": части}


def за_всё(сводка, история):
    """Всё, что заработано за всю историю, — из помесячного архива."""
    месяцы = (история or {}).get("months") or []
    всего = sum(деньги(м.get("total")) for м in месяцы)
    # Текущий месяц в архиве лежит на момент ночной сборки, а сводка свежее.
    totals = сводка.get("totals") or {}
    if месяцы and totals.get("month") is not None:
        всего = всего - деньги(месяцы[-1].get("total")) + деньги(totals["month"])
    по_годам = [{"name": str(г.get("y")), "value": деньги(г.get("total"))}
                for г in (история or {}).get("years") or []]
    return {"value": деньги(всего), "sub": "за всё время", "format": "money",
            "parts": по_годам[:4]}


def собрать(ключи=None):
    f = настройки()
    сводка = прочитать(f.get("summary"))
    if сводка is None:
        print(f"сводки нет по пути {f.get('summary')!r}: поправьте \"files\" в module.json",
              file=sys.stderr)
        sys.exit(1)
    все = блоки(сводка, прочитать(f.get("history")))
    return {k: v for k, v in все.items() if not ключи or k in ключи}


def main():
    команда = sys.argv[1] if len(sys.argv) > 1 else "collect"
    if команда == "collect":
        print(json.dumps(собрать(), ensure_ascii=False))
    elif команда == "query":
        if len(sys.argv) < 3:
            print("нужен ключ: main.py query <ключ> '{}'", file=sys.stderr)
            sys.exit(1)
        ключ = sys.argv[2]
        параметры = json.loads(sys.argv[3]) if len(sys.argv) > 3 and sys.argv[3] else {}
        if ключ == "month" and isinstance(параметры, dict) and ("from" in параметры or "to" in параметры):
            f = настройки()
            сводка = прочитать(f.get("summary")) or {}
            история = прочитать(f.get("history"))
            от, до = параметры.get("from", ""), параметры.get("to", "")
            # «Всё время» ядро присылает границей года ноль. Считать его по
            # дням нельзя: подневные данные живут месяц, а архив — с февраля.
            всё_время = not от or от <= "2000-01-01"
            ответ = за_всё(сводка, история) if всё_время else за_период(сводка, история, от, до)
            print(json.dumps(ответ, ensure_ascii=False))
            return
        д = собрать([ключ])
        if ключ not in д:
            print(f"блок {ключ!r} не посчитан", file=sys.stderr)
            sys.exit(1)
        print(json.dumps(д[ключ], ensure_ascii=False))
    else:
        print(f"неизвестная команда {команда!r}: бывают collect и query", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
