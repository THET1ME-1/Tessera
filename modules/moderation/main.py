def онлайн(_параметры=None):
    """Сколько человек держит соединение прямо сейчас и с чего они зашли.

    Считает не база, а Centrifugo: он и есть тот, кто держит соединения.
    Отметка `user_presence` для этого не годится — её пишут раз в пять минут,
    и по ней «сейчас» означает «за последние пять минут»: 875 против 1170.

    Платформу узнаём обходом присутствия в парных каналах — там лежит uid
    каждого подключённого, а платформа человека уже есть в базе приложения.
    Обход тысячи каналов стоит 0,8 с, поэтому разбивка живёт в кэше полторы
    минуты: общее число обновляется каждый тик, разбивка реже. Считать её по
    каналам `user:*` нельзя — там висят и каналы партнёров, которые сейчас
    оффлайн (2015 каналов против 1170 подключённых).
    """
    ист, _ = настройки()
    путь = ист.get("centrifugo", "/opt/centrifugo/config.json")
    адрес = ист.get("centrifugo_api", "http://127.0.0.1:9000")
    try:
        with open(путь, encoding="utf-8") as f:
            c = json.load(f)
        ключ = (c.get("http_api") or {}).get("key") or c.get("api_key") or ""
    except OSError as e:
        ошибка(f"конфиг Centrifugo не прочитался: {e}")
    if not ключ:
        ошибка("в конфиге Centrifugo нет ключа API")

    def спросить(путь_, тело, таймаут=4):
        req = urllib.request.Request(
            адрес.rstrip("/") + путь_, data=json.dumps(тело).encode(),
            headers={"X-API-Key": ключ, "Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=таймаут) as r:
            return json.loads(r.read().decode())

    try:
        инфо = спросить("/api/info", {}).get("result") or {}
    except Exception as e:
        ошибка(f"Centrifugo не ответил: {e}")
    людей = sum(u.get("num_users", 0) for u in инфо.get("nodes", []))
    соединений = sum(u.get("num_clients", 0) for u in инфо.get("nodes", []))

    пар, платформы = 0, {}
    свежий = _кэш_платформ()
    if свежий:
        пар, платформы = свежий["пар"], свежий["платформы"]
    else:
        try:
            каналы = list(((спросить("/api/channels", {"pattern": "pair:*"}).get("result") or {})
                           .get("channels") or {}).keys())
            пар = len(каналы)
            люди = set()
            for имя in каналы:
                try:
                    p = (спросить("/api/presence", {"channel": имя}, 3).get("result") or {}).get("presence") or {}
                    for кл in p.values():
                        if кл.get("user"):
                            люди.add(кл["user"])
                except Exception:
                    continue
            платформы = _платформы(люди, ист)
            _кэш_платформ(записать={"пар": пар, "платформы": платформы})
        except Exception:
            платформы = {}

    части = []
    if платформы:
        известно = платформы.get("android", 0) + платформы.get("ios", 0)
        части = [{"name": "Android", "value": платформы.get("android", 0)},
                 {"name": "iPhone", "value": платформы.get("ios", 0)}]
        # Остаток — те, кого не видно в парных каналах: одиночки, только что
        # подключившиеся, аккаунты без платформы. Без этой строки сумма частей
        # не сходится с числом наверху, и блок читается как ошибка.
        прочие = max(0, людей - известно)
        if прочие:
            части.append({"name": "не видно платформы", "value": прочие})
    if пар:
        части.append({"name": "пар на связи", "value": пар})

    хвост = f"{соединений} соединений" if соединений != людей else "человек на связи"
    return {"value": людей, "sub": хвост, "parts": части[:4]}


def _платформы(uids, ист):
    """Раскладка людей по системам. Поле `platform` пишут свежие сборки, а
    пуш-токен говорит об устройстве точно, поэтому смотрим оба признака."""
    db = ист.get("db", "")
    if not uids or not os.path.exists(db):
        return {}
    из_ = {"android": 0, "ios": 0, "нет": 0}
    conn = база(db)
    try:
        uids = list(uids)
        for i in range(0, len(uids), 900):
            часть = uids[i:i + 900]
            q = ",".join("?" * len(часть))
            for platform, apns, fcm in conn.execute(
                    f"SELECT platform, apns_token, fcm_token FROM users WHERE id IN ({q})", часть):
                p = (platform or "").lower()
                if p == "ios" or apns:
                    из_["ios"] += 1
                elif p == "android" or fcm:
                    из_["android"] += 1
                else:
                    из_["нет"] += 1
    finally:
        conn.close()
    return из_


_КЭШ_ПЛАТФОРМ = "/tmp/tessera_online_platforms.json"
_ЖИЗНЬ_КЭША = 90


def _кэш_платформ(записать=None):
    """Обход присутствия дорогой, а панель спрашивает блок раз в двадцать
    секунд и у каждого открытого окна. Полторы минуты — разумная давность для
    разбивки: общее число всё равно живое."""
    if записать is not None:
        try:
            with open(_КЭШ_ПЛАТФОРМ, "w", encoding="utf-8") as f:
                json.dump({"когда": time.time(), **записать}, f)
        except OSError:
            pass
        return None
    try:
        with open(_КЭШ_ПЛАТФОРМ, encoding="utf-8") as f:
            d = json.load(f)
        if time.time() - d.get("когда", 0) < _ЖИЗНЬ_КЭША:
            return d
    except (OSError, ValueError):
        pass
    return None


# ── лента ───────────────────────────────────────────────────────────────────

def условие_формата(имя):
    """Кусок SQL, оставляющий в ленте один формат. Незнакомое имя — пустота.

    Значение приходит из адреса, и «Видио» в нём не повод показать пустую
    ленту: неизвестный фильтр просто не применяется.
    """
    if имя not in ФОРМАТЫ:
        return ""
    расширения = ФОРМАТЫ[имя]
    if расширения is None:
        # «Фото» — всё, что не ролик и не звук. Отрицанием, а не списком:
        # перечислять png, jpg, webp, heic, gif, dng значит забыть седьмое
        # расширение и потерять снимки из ленты молча.
        не_они = ВИДЕО + ЗВУК
        return "(" + " AND ".join(
            f"lower(file) NOT LIKE '%{р}'" for р in не_они) + ")"
    return "(" + " OR ".join(
        f"lower(file) LIKE '%{р}'" for р in расширения) + ")"


def подходит_формату(файл, расширения):
    """Тот же отбор, что и в SQL, только для строк, уже прочитанных из базы."""
    р = os.path.splitext(файл or "")[1].lower()
    if расширения is None:
        return р not in ВИДЕО and р not in ЗВУК
    return р in (расширения or ())


def сосчитать(conn, условие, аргументы, через_кэш=False):
    """Сколько всего кадров под этим фильтром.

    Обычный фильтр считается запросом: `kind` и `group_id` берутся индексом.
    Формат — другое дело: колонки под него у `media` нет, отбор идёт по имени
    файла, и это полный проход по 1,2 млн строк, полторы секунды. Один раз
    терпимо, на каждой странице листания нет, поэтому число живёт полчаса в
    файле рядом с копиями оригиналов.

    Цена решения названа честно: полчаса лента может показывать вчерашний
    счёт. Сами кадры при этом всегда свежие — кэшируется только число.
    """
    сосчитать_ = lambda: conn.execute(              # noqa: E731
        f"SELECT count(*) FROM media{условие}", аргументы).fetchone()[0]
    if not через_кэш:
        return сосчитать_()

    _, корень = настройки()
    файл = os.path.join(корень, ФАЙЛ_СЧЁТА)
    ключ = условие + "|" + "|".join(str(а) for а in аргументы)
    склад = {}
    try:
        with open(файл, encoding="utf-8") as f:
            склад = json.load(f)
        запись = склад.get(ключ)
        if запись and time.time() - запись.get("когда", 0) < СРОК_СЧЁТА:
            return запись["сколько"]
    except (OSError, ValueError, AttributeError):
        # Файла нет, он битый или в нём не словарь: считаем заново и
        # перезаписываем. Счёт кадров не та вещь, ради которой стоит падать.
        склад = {}

    сколько = сосчитать_()
    склад[ключ] = {"сколько": сколько, "когда": time.time()}
    try:
        os.makedirs(корень, exist_ok=True)
        with open(файл, "w", encoding="utf-8") as f:
            json.dump(склад, f, ensure_ascii=False)
    except OSError as e:
        print(f"счёт не записался: {e}", file=sys.stderr)
    return сколько


def лента(параметры):
    ист, _ = настройки()
    db = ист.get("db", "")
    if not os.path.exists(db):
        ошибка(f"базы приложения нет по пути {db!r}")

    страница = int(параметры.get("page", "0") or 0)
    вид = параметры.get("kind", "") or ""
    виды = ВИДЫ.get(вид, ())
    # Пара — тот же фильтр, что и вид файла: разбор жалобы начинается с поиска
    # пары, а дальше модератору нужны её файлы, а не общий поток.
    пара = str(параметры.get("group", "") or "").strip()
    взрослый_фильтр = (параметры.get("adult", "") or "").strip()
    if взрослый_фильтр not in ("", "only", "hide"):
        взрослый_фильтр = ""
    if взрослый_фильтр == "only":
        return лента_с_замком(страница, вид, ист, db, пара,
                              параметры.get("fmt", "") or "")

    формат = параметры.get("fmt", "") or ""
    условия, аргументы = [], []
    if виды:
        условия.append("kind IN (" + ",".join("?" * len(виды)) + ")")
        аргументы += list(виды)
    if пара:
        условия.append("group_id = ?")
        аргументы.append(пара)
    по_формату = условие_формата(формат)
    if по_формату:
        условия.append(по_формату)
    условие = (" WHERE " + " AND ".join(условия)) if условия else ""

    conn = база(db)
    try:
        # rowid DESC — порядок вставки: свежее сверху. Сортировать по дате
        # внутри записи нельзя, её ставит загрузивший.
        строки = conn.execute(
            f"SELECT id, file, kind, group_id FROM media{условие} "
            f"ORDER BY rowid DESC LIMIT ? OFFSET ?",
            аргументы + [НА_СТРАНИЦЕ, страница * НА_СТРАНИЦЕ]).fetchall()
        всего = сосчитать(conn, условие, аргументы, через_кэш=bool(по_формату))
    finally:
        conn.close()

    # Кадры делаем до того, как собрать карточки: иначе готовый путь назвать
    # нечем, и браузер полезет за каждым кадром отдельным запросом, поднимая
    # процесс модуля на каждый.
    прогреть([(ид, файл) for ид, файл, *_ in строки], ист, ждать=True)

    взрослые = взрослые_для([г for _, _, _, г in строки])
    элементы = [карточка(ид, файл, вид_, группа, ист, взрослые)
                for ид, файл, вид_, группа in строки]

    # «Без 18+» режет уже собранную страницу: помеченных кадров на общем потоке
    # единицы, и страница от их пропажи почти не худеет. Обратный фильтр так не
    # сделаешь — помеченное лежит глубже первой страницы, поэтому «только 18+»
    # ушёл выше, в свою ветку.
    if взрослый_фильтр == "hide":
        элементы = [э for э in элементы if not э["adult"]]

    return {
        "items": элементы,
        "page": страница,
        "total": всего,
        "pages": (всего + НА_СТРАНИЦЕ - 1) // НА_СТРАНИЦЕ,
        "kinds": [и for и, в in ВИДЫ.items() if в],
        "formats": list(ФОРМАТЫ),
        "fmt": формат,
        "adult": взрослый_фильтр,
        "adultCount": sum(1 for э in элементы if э["adult"]),
        "group": пара,
    }


def прогреть(кадры, ист, ждать=False):
    """Просит генератор сделать миниатюры для тех кадров, которых ещё нет.

    На вход идут пары «id, имя файла»: имя нужно, чтобы не гонять генератор за
    звуком. Миниатюры у голосового не будет никогда, а на странице ленты их
    бывает под полсотни — столько же холостых запусков питона на каждый показ.

    Страницу ленты прогревают с ожиданием. Расписание тут не спасает: свежих
    кадров приходит около полусотни в минуту, лента смотрит ровно на них, и к
    открытию страницы верхние записи всегда моложе любого прогона. Один кадр
    стоит сотых долей секунды, вся страница — пары секунд, и это честнее сетки
    серых заглушек.

    Ждём только верх страницы, остальное уходит генератору фоном. Целая
    холодная страница (лента 18+ уводит в записи годовой давности, где кэша
    нет вовсе) в отведённое время не укладывается, а ядро ждёт модуль
    пятнадцать секунд и обрывает запрос — лучше отдать верх сразу. Низ
    дорисуется поштучно, при запросе картинки.

    Ролик стоит дороже снимка: его сперва тянут из бакета целиком, около трёх
    мегабайт, и только потом режут кадр — секунда против сотых долей. Поэтому
    роликов в ожидание идёт вчетверо меньше, иначе лента «только видео»
    открывалась бы восемь секунд вместо двух.

    Без ожидания зовут только про запас, для соседних страниц.
    """
    команда = ист.get("make")
    шаблон = ист.get("thumb", "")
    if not команда or not шаблон or not кадры:
        return
    нет, ролики = [], set()
    for i, имя in кадры:
        расширение = os.path.splitext(имя or "")[1].lower()
        if расширение in ЗВУК:
            continue
        if os.path.exists(шаблон.replace("{id}", i).replace("{w}", "512")):
            continue
        нет.append(i)
        if расширение in ВИДЕО:
            ролики.add(i)
    if not нет:
        return
    сразу = []
    if ждать:
        снимков = роликов = 0
        for i in нет:
            if i in ролики and роликов < 4:
                роликов += 1
            elif i not in ролики and снимков < 16:
                снимков += 1
            else:
                continue
            сразу.append(i)
    потом = [i for i in нет[:60] if i not in set(сразу)]
    try:
        if сразу:
            subprocess.run([*команда, "--ids", ",".join(сразу)],
                           timeout=10, check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if потом:
            subprocess.Popen([*команда, "--ids", ",".join(потом)],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                             start_new_session=True)
    except (OSError, subprocess.TimeoutExpired) as e:
        # Генератор — чужая программа: не запустился или не успел, лента всё
        # равно уходит. Промах закроется поштучно, при запросе картинки.
        print(f"генератор миниатюр не отозвался: {e}", file=sys.stderr)


def кадры_записи(первый, остальные, ролик=""):
    """Все ссылки на файлы одного воспоминания, обложка первой.

    Одиночный снимок лежит в `imageUrl`, альбом — в `imageUrls`, и обложка
    альбома обычно повторяется в списке. Порядок сохраняем: он же порядок
    кадров в приложении.

    Ролик живёт в своём поле `videoUrl`, а `imageUrl` держит его превью.
    Пока читались только картиночные поля, в ленте 18+ не было ни одного
    ролика: 182 помеченные записи проходили мимо, и «Видео» под замком
    показывало пустую ленту.
    """
    ссылки = ([первый] if первый else []) + list(остальные or []) + \
        ([ролик] if ролик else [])
    return [с for с in dict.fromkeys(ссылки) if с]


def кадры_с_замком():
    """Идентификаторы кадров с замком, свежие записи сверху.

    Отдельным списком, а не признаком в общей выборке: замок живёт в чужой
    базе, и отфильтровать им страницу `media` одним запросом нельзя.

    Берём ВСЕ кадры записи, а не одну обложку: замок пара ставит на
    воспоминание целиком, и альбом на сотню снимков приходил в ленту одной
    плиткой — остальное модератор не видел вовсе.

    Потолка тоже нет. Помеченных записей три тысячи, полный проход по ним
    стоит две десятых секунды, а любой предел режет как раз старое — то, ради
    чего в эту ленту и заходят.
    """
    ист, _ = настройки()
    if not (ист.get("pg") or os.environ.get("MODERATION_PG_DSN", "")):
        return []
    try:
        pg = postgres()
    except Exception:
        return []
    try:
        with pg.cursor() as cur:
            cur.execute("SET LOCAL statement_timeout = 8000")
            cur.execute(
                "SELECT data::jsonb ->> 'imageUrl', data::jsonb -> 'imageUrls', "
                "       data::jsonb ->> 'videoUrl' "
                "FROM memories "
                "WHERE (data::jsonb ->> 'isAdult') = 'true' "
                "  AND coalesce(deleted, false) = false "
                "ORDER BY created_at DESC")
            ряд = []
            for один, много, ролик in cur.fetchall():
                for ссылка in кадры_записи(один, много, ролик):
                    ид = ид_из_ссылки(ссылка)
                    if ид:
                        ряд.append(ид)
            return list(dict.fromkeys(ряд))
    except Exception:
        return []
    finally:
        try:
            pg.close()
        except Exception:
            pass


def лента_с_замком(страница, вид, ист, db, пара="", формат=""):
    """Страница ленты из кадров, помеченных парами как «для взрослых»."""
    все = кадры_с_замком()
    виды = ВИДЫ.get(вид, ())
    # Формат тут отбирается в питоне, а не запросом: строки всё равно уже
    # прочитаны по списку id из чужой базы, и второй фильтр в SQL ничего не
    # сэкономил бы.
    расширения = ФОРМАТЫ.get(формат) if формат in ФОРМАТЫ else ()
    conn = база(db)
    try:
        отобрано = []
        # Идём пачками: список приходит из чужой базы, а по нашей ходим
        # обычным IN. Порядок задаёт `media`, как и в общей ленте: дату внутри
        # записи ставит загрузивший, и альбом, подписанный маем, иначе тонет
        # ниже вчерашних кадров или всплывает выше них.
        for i in range(0, len(все), 900):
            часть = все[i:i + 900]
            места = ",".join("?" * len(часть))
            for ряд, ид, файл, вид_, группа in conn.execute(
                    f"SELECT rowid, id, file, kind, group_id FROM media "
                    f"WHERE id IN ({места})", часть):
                if виды and вид_ not in виды:
                    continue
                if пара and группа != пара:
                    continue
                if формат in ФОРМАТЫ and not подходит_формату(файл, расширения):
                    continue
                отобрано.append((ряд, ид, файл, вид_, группа))
        отобрано.sort(key=lambda с: -с[0])
    finally:
        conn.close()

    всего = len(отобрано)
    окно = отобрано[страница * НА_СТРАНИЦЕ:(страница + 1) * НА_СТРАНИЦЕ]
    прогреть([(ид, файл) for _, ид, файл, *_ in окно], ист, ждать=True)
    метки = {ид for _, ид, *_ in окно}
    элементы = [карточка(ид, файл, вид_, группа, ист, метки)
                for _, ид, файл, вид_, группа in окно]
    return {
        "items": элементы,
        "page": страница,
        "total": всего,
        "pages": max(1, (всего + НА_СТРАНИЦЕ - 1) // НА_СТРАНИЦЕ),
        "kinds": [и for и, в in ВИДЫ.items() if в],
        "formats": list(ФОРМАТЫ),
        "fmt": формат,
        "adult": "only",
        "adultCount": len(элементы),
        "group": пара,
    }


def взрослые_для(группы):
    """Кадры этих пар, помеченные в приложении как «для взрослых».

    Замок ставит сама пара в форме воспоминания, признак лежит в json-поле
    записи, а сами записи с 14 августа живут в Postgres. Спрашиваем только про
    пары текущей страницы: полный проход по воспоминаниям стоит секунды, а
    шестьдесят пар закрываются индексом по `group_id`.

    Замок считаем на каждом кадре записи, не только на обложке: иначе у
    альбома помеченным выглядел один снимок, а «Без 18+» прятал его одного и
    оставлял на виду остальные девяносто.

    Любая беда на той стороне стоит ровно одной подписи под кадром: лента
    важнее пометки, поэтому здесь молчаливое пустое множество вместо ошибки.
    """
    группы = [г for г in dict.fromkeys(группы) if г]
    if not группы:
        return set()
    ист, _ = настройки()
    if not (ист.get("pg") or os.environ.get("MODERATION_PG_DSN", "")):
        return set()
    try:
        pg = postgres()
    except Exception:
        return set()
    try:
        with pg.cursor() as cur:
            cur.execute("SET LOCAL statement_timeout = 4000")
            cur.execute(
                "SELECT data::jsonb ->> 'imageUrl', data::jsonb -> 'imageUrls', "
                "       data::jsonb ->> 'videoUrl' "
                "FROM memories "
                "WHERE group_id = ANY(%s) "
                "  AND (data::jsonb ->> 'isAdult') = 'true' "
                "  AND coalesce(deleted, false) = false", (группы,))
            найдено = set()
            for один, много, ролик in cur.fetchall():
                for ссылка in кадры_записи(один, много, ролик):
                    ид = ид_из_ссылки(ссылка)
                    if ид:
                        найдено.add(ид)
            return найдено
    except Exception:
        return set()
    finally:
        try:
            pg.close()
        except Exception:
            pass


def ид_из_ссылки(ссылка):
    """Идентификатор файла из ссылки вида `pb://media/<id>/<имя>`.

    Так воспоминание в Postgres указывает на строку в `media`: собственного
    поля с файлом у него нет. Всё, что на этот вид не похоже, отдаёт пустоту.
    """
    куски = (ссылка or "").split("/")
    if len(куски) < 5 or not куски[0].startswith("pb:"):
        return ""
    return куски[3]


def карточка(ид, файл, вид, группа, ист, взрослые):
    """Один кадр ленты со всем, что нужно модератору с одного взгляда."""
    готовый = ""
    шаблон = ист.get("thumb", "")
    if шаблон:
        для_512 = шаблон.replace("{id}", ид).replace("{w}", "512")
        if os.path.exists(для_512):
            готовый = для_512
    расширение = os.path.splitext(файл or "")[1].lower()
    звук = расширение in ЗВУК
    return {
        "id": ид,
        # Готовый путь называем сразу: ядро отдаст файл, не поднимая ради
        # каждого кадра отдельный процесс модуля. Кадра ещё нет — оставляем
        # прежний адрес, там миниатюра сделается на месте. У звука адреса нет
        # вовсе: миниатюры не будет, и ссылка на неё обернулась бы вечной
        # надписью «кадр ещё готовится» на пятнадцати тысячах плиток.
        "url": "" if звук else (
            f"/api/file?src=moderation:thumb&id={ид}&type=image/webp"
            f"&path={quote(готовый)}" if готовый else
            f"/api/file?src=moderation:thumb&id={ид}"),
        "caption": человечный(вид),
        "kind": вид,
        "group": группа,
        "ts": метка_времени(файл),
        "adult": ид in взрослые,
        "video": расширение in ВИДЕО,
        "audio": звук,
        # Ролик и голосовое разбираются не глазами: кадр говорит, что внутри,
        # а жалоба обычно про звук и движение. Тот же оригинал, только без
        # просьбы скачать, — браузер проигрывает его прямо в панели.
        "play": (f"/api/file?src=moderation:original&id={ид}"
                 if расширение in ВИДЕО or звук else ""),
        # Адрес оригинала называет модуль, а не панель: панель не знает ни
        # ключей этого модуля, ни того, что у кадра вообще бывает исходник.
        "download": f"/api/file?src=moderation:original&id={ид}&download=1",
    }


def метка_времени(имя):
    """Секунды загрузки, вытащенные из имени файла.

    В таблице `media` даты нет ни одной колонкой, зато приложение кладёт метку
    прямо в имя: `memory_1786968914693_…`, `fill_1786993617496_140_…`. Берём
    первое тринадцатизначное число, похожее на миллисекунды нашего века:
    короткие числа рядом — счётчик кадра холста, а не время. Нет метки — ноль,
    и подпись под кадром просто не рисуется.
    """
    for кусок in re.findall(r"\d{13}", имя or ""):
        мс = int(кусок)
        if 1_577_836_800_000 <= мс <= 4_102_444_800_000:  # 2020…2100
            return мс // 1000
    return 0


def человечный(вид):
    for имя, виды in ВИДЫ.items():
        if вид in виды:
            return имя
    return вид


# ── миниатюра ───────────────────────────────────────────────────────────────

def миниатюра(параметры):
    """Возвращает путь к готовой миниатюре.

    Миниатюры делает отдельный крон приложения и кладёт их в свой кэш. Модуль
    только называет файл: ядро проверит, что он внутри объявленного корня, и
    отдаст сам. Штатные миниатюры хранилища тут не годятся — для webp они
    перекодируются в png тяжелее оригинала.
    """
    ист, корень = настройки()
    id_ = параметры.get("id", "")
    if not id_ or "/" in id_ or ".." in id_:
        ошибка("нужен id файла")

    шаблон = ист.get("thumb", "")
    if not шаблон:
        ошибка("в module.json не задан шаблон пути к миниатюре")

    # Просят один размер, а в кэше бывает другой: лайтбокс хочет крупный кадр,
    # а крон успел сделать только плитку. Отдать меньший лучше, чем отказать.
    хотят = параметры.get("w", "512")
    for w in [хотят] + [р for р in ("1600", "512") if р != хотят]:
        путь = шаблон.replace("{id}", id_).replace("{w}", w)
        if os.path.exists(путь):
            return {"path": путь, "type": "image/webp"}

    # Кэш греет крон приложения, но он берёт последние шестьсот записей раз в
    # десять минут, а загружают быстрее — свежий кадр не успевает попасть в
    # прогрев никогда. Поэтому промах не ждём, а просим генератор сделать
    # именно этот файл: у него для такого есть отдельный режим.
    команда = ист.get("make")
    if команда:
        try:
            subprocess.run([*команда, "--ids", id_], timeout=8, check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except (OSError, subprocess.TimeoutExpired) as e:
            print(f"генератор миниатюр не отозвался: {e}", file=sys.stderr)
        for w in [хотят, "512", "1600"]:
            путь = шаблон.replace("{id}", id_).replace("{w}", w)
            if os.path.exists(путь):
                return {"path": путь, "type": "image/webp"}

    ошибка(f"миниатюры нет и сделать не вышло: {id_}")


# ── подпись оригинала ───────────────────────────────────────────────────────

def подписать(путь, группа, сведения):
    """Кладёт в файл описание, дату съёмки и координаты.

    Оригиналы приложения приходят пустыми: снимок перекодируется в webp, и
    вместе с весом уходит всё, что записала камера. Скачанный кадр ложится в
    галерею без даты, без места и без признака, чьей паре он принадлежит.

    Описание — голый номер пары, без слов вокруг: с ним модератор уходит в
    поиск и в переписку, а «пара такая-то» пришлось бы вычищать руками в
    каждой галерее.

    Пишем тремя способами сразу: Immich читает XMP, Google Photos — IPTC,
    программы постарше — EXIF. Одного мало, описание увидит одна галерея из
    трёх. В webp живёт только XMP, и остальные два тега там молча пропадают —
    это нормально, ради них команда не разбивается на части.

    exiftool ставится отдельным пакетом, и его может не оказаться. Тогда
    оригинал уходит как есть: файл без описания лучше, чем отказ в скачивании.
    """
    метки = ["-overwrite_original", "-q", "-m",
             # IPTC по старой памяти хранит текст латиницей, и название места
             # вроде «Алматы, Казахстан» превращается в частокол вопросов.
             # Кодировку приходится называть дважды: разбор строки и пометка
             # внутри файла, иначе её не прочтёт чужая программа.
             "-charset", "iptc=UTF8", "-IPTC:CodedCharacterSet=UTF8",
             f"-XMP-dc:Description={группа}",
             f"-IPTC:Caption-Abstract={группа}",
             f"-EXIF:ImageDescription={группа}"]

    снято = сведения.get("снято")
    if снято:
        метки += [f"-EXIF:DateTimeOriginal={снято}", f"-EXIF:CreateDate={снято}",
                  f"-XMP:DateTimeOriginal={снято}", f"-XMP:CreateDate={снято}"]
        сдвиг = сведения.get("сдвиг")
        if сдвиг:
            метки += [f"-EXIF:OffsetTimeOriginal={сдвиг}", f"-EXIF:OffsetTime={сдвиг}"]

    широта, долгота = сведения.get("широта"), сведения.get("долгота")
    if широта is not None and долгота is not None:
        # Сторону света задаём отдельно: exiftool хранит координату модулем, и
        # без стороны Рио оказывается в северном полушарии — карта в Immich
        # соврёт на семь тысяч километров.
        метки += [f"-GPSLatitude={abs(широта)}", f"-GPSLatitudeRef={'N' if широта >= 0 else 'S'}",
                  f"-GPSLongitude={abs(долгота)}", f"-GPSLongitudeRef={'E' if долгота >= 0 else 'W'}"]

    место = сведения.get("место")
    if место:
        метки += [f"-XMP:Location={место}", f"-IPTC:Sub-location={место}"]

    try:
        subprocess.run(["exiftool", *метки, путь], timeout=20, check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.TimeoutExpired) as e:
        print(f"описание не вписалось: {e}", file=sys.stderr)


def сведения_кадра(ид, группа):
    """Дата и место кадра — из записи воспоминания, где он лежит.

    В самом файле их нет, а в записи есть: `createdAt` — дата, которую пара
    поставила снимку, `latitude`/`longitude`/`locationName` — место, если его
    отметили. Координаты стоят у каждого пятого воспоминания.

    Ищем внутри пары: связь кадра с записью живёт только в json-поле, а
    отдельного столбца под неё нет. По группе запрос идёт индексом и стоит
    пару миллисекунд, полный поиск по тексту — четыреста.

    Любая беда на той стороне стоит подписи, а не скачивания: нет группы, нет
    строки подключения, база молчит — кадр уходит с одним описанием.
    """
    if not группа or not ид:
        return {}
    try:
        pg = postgres()
    except (SystemExit, Exception) as e:        # noqa: BLE001 — подпись не обязана быть
        print(f"сведения о кадре не достались: {e}", file=sys.stderr)
        return {}
    try:
        with pg.cursor() as cur:
            cur.execute("SET LOCAL statement_timeout = 4000")
            cur.execute(
                "SELECT data::jsonb ->> 'createdAt', data::jsonb ->> 'tz', "
                "       data::jsonb ->> 'latitude', data::jsonb ->> 'longitude', "
                "       data::jsonb ->> 'locationName' "
                "FROM memories WHERE group_id = %s AND data::text LIKE %s "
                "  AND coalesce(deleted, false) = false LIMIT 1",
                (группа, f"%{ид}%"))
            строка = cur.fetchone()
    except Exception as e:                      # noqa: BLE001
        print(f"сведения о кадре не достались: {e}", file=sys.stderr)
        return {}
    finally:
        try:
            pg.close()
        except Exception:                       # noqa: BLE001
            pass
    if not строка:
        return {}

    когда, пояс, широта, долгота, место = строка
    итог = {}
    снято, сдвиг = время_съёмки(когда, пояс)
    if снято:
        итог["снято"] = снято
        if сдвиг:
            итог["сдвиг"] = сдвиг
    try:
        if широта and долгота:
            итог["широта"], итог["долгота"] = float(широта), float(долгота)
    except (TypeError, ValueError):
        pass
    if место:
        итог["место"] = место
    return итог


def сведения_для_подписи(ид, группа, имя):
    """Всё, что известно о кадре к моменту скачивания.

    Сперва запись воспоминания: там дата, которую пара поставила снимку, и
    место. Виджеты, аватарки и маскоты в воспоминаниях не лежат — а это
    половина ленты, — и для них остаётся метка загрузки из имени файла.
    Момент в ней всемирный: часового пояса у такого кадра взять неоткуда, а
    ради минут ходить в базу за поясом пары незачем — модерации важен день.

    Имя без метки даты не даёт: соврать числом хуже, чем оставить кадр без
    него. С неверной датой он встанет в галерее не на своё место, и найти его
    будет труднее, чем без даты вовсе.
    """
    сведения = сведения_кадра(ид, группа)
    if сведения.get("снято"):
        return сведения
    метка = метка_времени(имя)
    if метка:
        from datetime import datetime, timezone     # noqa: PLC0415
        момент = datetime.fromtimestamp(метка, timezone.utc).isoformat()
        снято, сдвиг = время_съёмки(момент, пояс_пары(группа))
        if снято:
            сведения["снято"] = снято
            if сдвиг:
                сведения["сдвиг"] = сдвиг
    return сведения


def пояс_пары(группа):
    """Часовой пояс пары — из любой её записи воспоминания.

    Нужен кадрам, которых в воспоминаниях нет: виджету, аватарке, маскоту. У
    них есть только метка загрузки во всемирном времени, и без пояса снимок,
    сделанный во Владивостоке вечером, попадает в галерею на утро того же дня,
    а около полуночи — и вовсе на соседние сутки.
    """
    if not группа:
        return ""
    try:
        pg = postgres()
    except (SystemExit, Exception) as e:        # noqa: BLE001
        print(f"пояс пары не достался: {e}", file=sys.stderr)
        return ""
    try:
        with pg.cursor() as cur:
            cur.execute("SET LOCAL statement_timeout = 3000")
            cur.execute(
                "SELECT data::jsonb ->> 'tz' FROM memories "
                "WHERE group_id = %s AND data::jsonb ->> 'tz' IS NOT NULL "
                "ORDER BY created_at DESC LIMIT 1", (группа,))
            строка = cur.fetchone()
    except Exception as e:                      # noqa: BLE001
        print(f"пояс пары не достался: {e}", file=sys.stderr)
        return ""
    finally:
        try:
            pg.close()
        except Exception:                       # noqa: BLE001
            pass
    return (строка[0] if строка else "") or ""


def время_съёмки(когда, пояс):
    """Метка `createdAt` записи → дата в том виде, в каком её носят снимки.

    В записи момент лежит в UTC, а рядом — часовой пояс пары. Галереи ставят
    снимок на ту минуту, что записана в кадре, поэтому переводим момент в
    местное время пары и отдельно называем сдвиг: без него вечерний снимок из
    Владивостока попадает в галерее на утро.
    """
    if not когда:
        return "", ""
    from datetime import datetime, timedelta     # noqa: PLC0415
    строка = str(когда).replace("Z", "+00:00")
    try:
        момент = datetime.fromisoformat(строка)
    except ValueError:
        return "", ""
    сдвиг = ""
    м = re.match(r"^([+-])(\d{2}):(\d{2})$", str(пояс or "").strip())
    if м:
        знак = 1 if м.group(1) == "+" else -1
        часы, минуты = int(м.group(2)), int(м.group(3))
        момент = момент + знак * timedelta(hours=часы, minutes=минуты)
        сдвиг = f"{м.group(1)}{м.group(2)}:{м.group(3)}"
    return момент.strftime("%Y:%m:%d %H:%M:%S"), сдвиг


