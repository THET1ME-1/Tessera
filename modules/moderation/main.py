    try:
        всего = conn.execute("SELECT count(*) FROM media").fetchone()[0]
        по_видам = dict(conn.execute("SELECT kind, count(*) FROM media GROUP BY kind"))
    finally:
        conn.close()

    ряды = []
    учтено = set()
    for имя, виды in ВИДЫ.items():
        if not виды:
            continue
        n = sum(по_видам.get(в, 0) for в in виды)
        учтено.update(виды)
