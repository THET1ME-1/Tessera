def оригинал(параметры):
    """Путь к исходному файлу — тому, что загрузил человек.

    Лента живёт на миниатюрах: они webp, обрезаны по длинной стороне и
    перекодированы. Для жалобы, письма или разбора нужен файл как есть.

    Исходники приложения лежат в бакете, а не на диске, поэтому оригинал
    приходится выкачивать. Копия ложится внутрь корня модуля: ядро отдаёт
    только то, что лежит там, и на путь во временную папку ответит отказом.
    """
    ист, корень = настройки()
    ид = параметры.get("id", "")
    if not ид or "/" in ид or ".." in ид:
        ошибка("нужен id файла")

    db = ист.get("db", "")
    if not os.path.exists(db):
        ошибка(f"базы приложения нет по пути {db!r}")
    conn = база(db)
    try:
        строка = conn.execute("SELECT file, group_id FROM media WHERE id=?",
                              (ид,)).fetchone()
    finally:
        conn.close()
    if not строка or not строка[0]:
        ошибка(f"файла {ид!r} нет в хранилище приложения")
    имя, группа = строка[0], строка[1] or ""

    склад = os.path.join(корень, ПАПКА_КОПИЙ)
    os.makedirs(склад, exist_ok=True)
    # Имя копии начинается с id: у разных записей файлы зовутся одинаково
    # («avatar.jpg»), и без него они затирали бы друг друга. Само имя берём
    # только последним куском — оно из чужой базы, и «../» в нём уводит копию
    # за корень.
    # Дату съёмки ставит тумблер в ленте, и режимов поэтому два. Копия живёт
    # сутки и отдаётся повторно, так что режим входит в её имя: иначе
    # переключённый тумблер возвращал бы вчерашний файл.
    расширение = os.path.splitext(имя)[1].lower()
    # Ролик и голосовое подписывать нечем и незачем: даты съёмки у них в
    # записи нет, а exiftool на мегабайтах видео стоит секунды. Копия у них
    # поэтому одна на оба режима тумблера — иначе за один просмотр файл
    # выкачивался бы из бакета дважды.
    подписываем = расширение not in ВИДЕО and расширение not in ЗВУК
    с_датой = str(параметры.get("date", "1")).strip() not in ("0", "false", "no")
    метка = "" if с_датой or not подписываем else "_nd"
    цель = os.path.join(склад, f"{ид}{метка}_{os.path.basename(имя)}")

    if not os.path.exists(цель):
        if not выкачать(ид, имя, цель, ист):
            ошибка(f"оригинал {ид!r} не достать ни с диска, ни из бакета")
        # Подписываем только свежую копию: у лежащей подпись уже стоит, а
        # второй проход exiftool стоил бы столько же, сколько первый.
        if подписываем:
            сведения = сведения_для_подписи(ид, группа, имя)
            if not с_датой:
                сведения.pop("снято", None)
                сведения.pop("сдвиг", None)
            подписать(цель, группа, сведения)

    тип = ТИПЫ.get(os.path.splitext(имя)[1].lower()) or mimetypes.guess_type(имя)[0]
    return {"path": цель, "type": тип or "application/octet-stream", "name": имя}


def выкачать(ид, имя, цель, ист):
    """Кладёт исходник в `цель`: сперва диск, при промахе — бакет.

    Диск проверяется первым не из осторожности, а потому, что так дешевле:
    пока файл лежит рядом, платить за выкачку из бакета незачем.
    """
    склад = ист.get("storage", "")
    коллекция = ист.get("collection", КОЛЛЕКЦИЯ)
    if склад:
        свой = os.path.join(склад, коллекция, ид, имя)
        if os.path.exists(свой):
            shutil.copyfile(свой, цель)
            return True

    хранилище = _хранилище(ист)
    if хранилище is None:
        return False
    try:
        with хранилище.Source(ид, имя, collection=коллекция) as исходник:
            if not исходник.path:
                return False
            shutil.copyfile(исходник.path, цель)
    except Exception as e:                     # noqa: BLE001 — модуль не должен падать
        print(f"оригинал не выкачался: {e}", file=sys.stderr)
        return False
    return True


def _хранилище(ист):
    """Загружает `pb_storage.py` приложения — тот, что умеет доставать из бакета.

    Скрипт живёт рядом с приложением, а не в репозитории модуля: он знает имя
    бакета и ключи. Путь к нему задаётся в module.json ключом "pbstorage"; без
    него модуль умеет только диск.
    """
    путь = ист.get("pbstorage", "")
    if not путь or not os.path.exists(путь):
        return None
    спец = importlib.util.spec_from_file_location("pb_storage", путь)
    if спец is None or спец.loader is None:
        return None
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except Exception as e:                     # noqa: BLE001
        print(f"pb_storage не загрузился: {e}", file=sys.stderr)
        return None
    return модуль


def убрать_копии(корень):
    """Сносит выкачанные оригиналы старше суток.

    Зовётся из расписания вместе со сводкой. Без уборки папка растёт молча:
    один разбор жалобы на альбом — это десятки файлов по несколько мегабайт.
    """
    склад = os.path.join(корень, ПАПКА_КОПИЙ)
    if not os.path.isdir(склад):
        return
    порог = time.time() - СРОК_КОПИЙ
    for имя in os.listdir(склад):
        путь = os.path.join(склад, имя)
        try:
            if os.path.isfile(путь) and os.path.getmtime(путь) < порог:
                os.remove(путь)
        except OSError:
            pass


