def база(путь):
    conn = sqlite3.connect(f"file:{путь}?mode=ro", uri=True, timeout=5)
    conn.execute("PRAGMA query_only = ON")
    return conn


def ошибка(текст):
    print(текст, file=sys.stderr)
    sys.exit(1)


